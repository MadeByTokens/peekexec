#!/bin/sh
# shellcheck disable=SC2016  # backticks below are literal Markdown
# Regenerate docs/cli.md and the man page from the binary's own help output.
set -eu
cd "$(dirname "$0")/.."
cargo build -q -p peekexec
bin=target/debug/peekexec
{
  printf '# peekexec CLI contract\n\n'
  printf 'Generated by `scripts/gen-cli-doc.sh` from the binary; a test fails if the\n'
  printf 'agent guide below drifts from `peekexec help agents`.\n\n'
  printf '## `peekexec --help`\n\n```\n'
  "$bin" --help
  printf '```\n\n## `peekexec help agents`\n\n```\n'
  "$bin" help agents
  printf '```\n\n## `--json` output\n\nSee `peekexec help schema` for the full JSON Schema.\n'
} > docs/cli.md
"$bin" help man > packaging/man/peekexec.1
